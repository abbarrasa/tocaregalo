const { test, expect } = require('../../frontend/node_modules/@playwright/test')
const fs = require('node:fs/promises')
const { randomUUID } = require('node:crypto')
const { initial, changed } = require('./identity-data')
test.skip(process.env.IDENTITY_E2E !== '1', 'Requires the guarded identity graph')
test.use({ trace: 'off', video: 'off', screenshot: 'off' })
async function privateFill(locator, value) {
  try { await locator.fill(value) } catch { throw new Error('Could not fill a synthetic credential field.') }
}
async function login(page, email = 'ana@example.test', password = initial) {
  await page.goto('/login')
  await page.getByLabel('Correo electrónico', { exact: true }).fill(email)
  await privateFill(page.getByLabel('Contraseña', { exact: true }), password)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
}
async function account(page) {
  await expect(page.getByRole('link', { name: 'Mi cuenta', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Mi cuenta', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Mi cuenta', exact: true })).toBeVisible()
}
async function logout(page) {
  await page.goto('/dashboard')
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Iniciar sesión' })).toBeVisible()
}
test.beforeEach(async () => {
  const path = `${process.env.IDENTITY_CONTROL_DIR}/${randomUUID()}`
  await fs.writeFile(`${path}.request.json`, JSON.stringify({ action: 'reset' }), { mode: 0o600 })
  await expect.poll(async () => { try { return await fs.readFile(`${path}.response.json`, 'utf8') } catch { return 'waiting' } }, { timeout: 60000 }).toBe('ok')
  await fs.unlink(`${path}.response.json`)
})
test('own profile canonical save, reload, surname clear, keyboard and phone input', async ({ page }) => {
  await page.goto('/account')
  await expect(page.getByRole('heading', { name: 'Iniciar sesión' })).toBeVisible()
  await login(page); await account(page)
  await page.getByRole('button', { name: 'Guardar datos', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('No hay cambios')
  await page.getByLabel('Nombre', { exact: true }).fill('  Eva  ')
  await page.getByLabel('Apellidos (opcional)', { exact: true }).fill('  García  ')
  await page.getByLabel('Correo electrónico', { exact: true }).fill('eva@example.test')
  const phone = page.getByLabel('Número de teléfono', { exact: true })
  await phone.fill('')
  await phone.pressSequentially('+44 (700)-123 456')
  await expect(phone).toHaveValue('+44700123456')
  await phone.press('Enter')
  await expect(page.getByRole('status')).toContainText('Datos actualizados')
  await expect(page.getByLabel('Nombre', { exact: true })).toHaveValue('Eva')
  await page.reload()
  await expect(page.getByLabel('Apellidos (opcional)', { exact: true })).toHaveValue('García')
  await page.getByLabel('Apellidos (opcional)', { exact: true }).fill('')
  await page.getByRole('button', { name: 'Guardar datos', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Datos actualizados')
  await page.reload()
  await expect(page.getByLabel('Apellidos (opcional)', { exact: true })).toHaveValue('')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('link', { name: 'Volver al panel' }).click()
  await expect(page.getByText('Hola, Eva.')).toBeVisible()
  await logout(page); await login(page, 'eva@example.test')
  await expect(page.getByText('Hola, Eva.')).toBeVisible()
})
test('duplicate identifiers and mass assignment preserve own and other accounts', async ({ page }) => {
  await login(page); await account(page)
  await page.getByLabel('Correo electrónico', { exact: true }).fill('super@example.test')
  await page.getByRole('button', { name: 'Guardar datos', exact: true }).click()
  await expect(page.getByLabel('Correo electrónico', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByLabel('Correo electrónico', { exact: true })).toBeFocused()
  await page.getByLabel('Correo electrónico', { exact: true }).fill('ana@example.test')
  await page.getByLabel('Número de teléfono', { exact: true }).fill('+34 (600)-123457')
  await page.getByRole('button', { name: 'Guardar datos', exact: true }).click()
  await expect(page.getByLabel('Número de teléfono', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  const rejected = await page.evaluate(async () => {
    const { csrfToken } = await (await fetch('/api/csrf')).json()
    const result = await fetch('/api/me', { method: 'PATCH', headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': csrfToken }, body: JSON.stringify({ id: 2, roles: ['ROLE_SUPER_ADMIN'], firstName: 'Forbidden' }) })
    const own = await (await fetch('/api/me')).json()
    return result.status === 422 && own.firstName === 'Ana' && own.email === 'ana@example.test' && own.phone === '+34600123456' && own.roles.length === 1 && own.roles[0] === 'ROLE_USER'
  })
  expect(rejected).toBe(true)
  await logout(page); await login(page, 'super@example.test'); await account(page)
  await expect(page.getByLabel('Nombre', { exact: true })).toHaveValue('Super')
  await expect(page.getByLabel('Número de teléfono', { exact: true })).toHaveValue('+34600123457')
  await page.getByLabel('Apellidos (opcional)', { exact: true }).fill('Admin')
  await page.getByRole('button', { name: 'Guardar datos', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Datos actualizados')
  await logout(page); await login(page); await account(page)
  await expect(page.getByLabel('Nombre', { exact: true })).toHaveValue('Ana')
  await expect(page.getByLabel('Apellidos (opcional)', { exact: true })).toHaveValue('')
})
test('exact password change retains session and replaces login credential', async ({ page }) => {
  await login(page); await account(page)
  const input = page.getByLabel('Nueva contraseña', { exact: true })
  await privateFill(input, 'short')
  await page.getByRole('button', { name: 'Cambiar contraseña', exact: true }).click()
  await expect(input).toBeFocused()
  await privateFill(input, changed)
  await page.getByRole('button', { name: 'Cambiar contraseña', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Contraseña actualizada')
  expect(await input.inputValue() === '').toBe(true)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Guardar datos', exact: true })).toBeVisible()
  await logout(page); await login(page)
  await expect(page.getByRole('alert')).toContainText('no son correctos')
  await login(page, 'ana@example.test', changed)
  await expect(page.getByText('Hola, Ana.')).toBeVisible()
})
test('network failure retains draft and expired session cannot save or replay', async ({ page }) => {
  await login(page); await account(page)
  await page.getByLabel('Nombre', { exact: true }).fill('Unsaved')
  await page.route('**/api/me', route => route.request().method() === 'PATCH' ? route.abort('failed') : route.continue())
  await page.getByRole('button', { name: 'Guardar datos', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('No se pudo conectar')
  await expect(page.getByLabel('Nombre', { exact: true })).toHaveValue('Unsaved')
  await page.unroute('**/api/me')
  const csrf = await (await page.request.get('/api/csrf')).json()
  expect((await page.request.post('/api/logout', { headers: { 'X-CSRF-Token': csrf.csrfToken } })).status()).toBe(204)
  await page.getByRole('button', { name: 'Guardar datos', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Iniciar sesión' })).toBeVisible()
  await login(page); await account(page)
  await expect(page.getByLabel('Nombre', { exact: true })).toHaveValue('Ana')
})
